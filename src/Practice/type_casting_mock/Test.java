package Practice.type_casting_mock;

public class Test {
	public static void main(String[] args) {
		//implicit type casting 
		int num=10;
		float num2=num;
		System.out.println("the value of num2 is "+num2);
		
		//explicit type casting 
		int num3=128;
		byte num4=(byte) num3;
		System.out.println("the value of num4 is "+num4);
	}

}
